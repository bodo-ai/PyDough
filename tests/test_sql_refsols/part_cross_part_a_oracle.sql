WITH "_s0" AS (
  SELECT DISTINCT
    SBTICKEREXCHANGE
  FROM MAIN.SBTICKER
), "_s1" AS (
  SELECT DISTINCT
    SBCUSTSTATE
  FROM MAIN.SBCUSTOMER
), "_s11" AS (
  SELECT
    "_s3".SBCUSTSTATE,
    "_s2".SBTICKEREXCHANGE,
    COUNT(*) AS N_ROWS
  FROM "_s0" "_s2"
  CROSS JOIN "_s1" "_s3"
  JOIN MAIN.SBCUSTOMER SBCUSTOMER
    ON SBCUSTOMER.SBCUSTSTATE = "_s3".SBCUSTSTATE
  JOIN MAIN.SBTRANSACTION SBTRANSACTION
    ON SBCUSTOMER.SBCUSTID = SBTRANSACTION.SBTXCUSTID
  JOIN MAIN.SBTICKER SBTICKER
    ON SBTICKER.SBTICKEREXCHANGE = "_s2".SBTICKEREXCHANGE
    AND SBTICKER.SBTICKERID = SBTRANSACTION.SBTXTICKERID
  GROUP BY
    "_s3".SBCUSTSTATE,
    "_s2".SBTICKEREXCHANGE
)
SELECT
  "_s1".SBCUSTSTATE AS state,
  "_s0".SBTICKEREXCHANGE AS exchange,
  COALESCE("_s11".N_ROWS, 0) AS n
FROM "_s0" "_s0"
CROSS JOIN "_s1" "_s1"
LEFT JOIN "_s11" "_s11"
  ON "_s0".SBTICKEREXCHANGE = "_s11".SBTICKEREXCHANGE
  AND "_s1".SBCUSTSTATE = "_s11".SBCUSTSTATE
ORDER BY
  1 NULLS FIRST,
  2 NULLS FIRST
