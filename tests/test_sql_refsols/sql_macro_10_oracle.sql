WITH "_0" AS (
  SELECT
    '1-URGENT' AS PRIORITY_NAME,
    1 AS PRIORITY_VALUE
  UNION ALL
  SELECT
    '2-HIGH' AS "2-HIGH",
    2 AS "2"
  UNION ALL
  SELECT
    '3-MEDIUM' AS "3-MEDIUM",
    3 AS "3"
  UNION ALL
  SELECT
    '4-NOT SPECIFIED' AS "4-NOT SPECIFIED",
    4 AS "4"
  UNION ALL
  SELECT
    '5-LOW' AS "5-LOW",
    5 AS "5"
), "_t" AS (
  SELECT
    O_ORDERPRIORITY,
    NTILE(10) OVER (ORDER BY O_TOTALPRICE, O_ORDERKEY) AS "_w"
  FROM TPCH.ORDERS
), "_s1" AS (
  SELECT
    O_ORDERPRIORITY,
    COUNT(*) AS N_ROWS
  FROM "_t"
  WHERE
    "_w" = 1
  GROUP BY
    O_ORDERPRIORITY
)
SELECT
  "_0".PRIORITY_NAME AS prio,
  COALESCE("_s1".N_ROWS, 0) AS n_chosen
FROM "_0" "_0"
LEFT JOIN "_s1" "_s1"
  ON "_0".PRIORITY_NAME = "_s1".O_ORDERPRIORITY
