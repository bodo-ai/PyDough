WITH "_1" AS (
  SELECT DISTINCT
    REGEXP_SUBSTR(P.P_NAME, '[^ ]+', 1, "_0".LVL) AS COLOR
  FROM PART P
  CROSS JOIN LATERAL (
    SELECT
      LEVEL AS LVL
    FROM DUAL
    CONNECT BY LEVEL <= REGEXP_COUNT(P.P_NAME, '[^ ]+')
  )"_0"
)
SELECT
  COLOR AS color
FROM "_1"
ORDER BY
  1 NULLS FIRST
FETCH FIRST 5 ROWS ONLY
