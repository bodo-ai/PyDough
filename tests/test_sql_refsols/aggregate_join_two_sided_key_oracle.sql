SELECT
  NVL(CUSTOMER.C_MKTSEGMENT, '') || ' - ' || NVL(NATION.N_NAME, '') AS label,
  COUNT(*) AS n
FROM TPCH.CUSTOMER CUSTOMER
JOIN TPCH.NATION NATION
  ON CUSTOMER.C_NATIONKEY = NATION.N_NATIONKEY
GROUP BY
  NVL(CUSTOMER.C_MKTSEGMENT, '') || ' - ' || NVL(NATION.N_NAME, '')
ORDER BY
  1 NULLS FIRST
