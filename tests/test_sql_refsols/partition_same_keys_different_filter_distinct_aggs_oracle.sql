WITH "_t0" AS (
  SELECT
    AVG(O_TOTALPRICE) AS AVG_O_TOTALPRICE
  FROM MAIN.ORDERS
  WHERE
    EXTRACT(YEAR FROM CAST(O_ORDERDATE AS DATE)) = 1995
  GROUP BY
    O_ORDERSTATUS
), "_s0" AS (
  SELECT
    MAX(AVG_O_TOTALPRICE) AS MAX_AVG_O_TOTALPRICE,
    MIN(AVG_O_TOTALPRICE) AS MIN_AVG_O_TOTALPRICE
  FROM "_t0"
), "_t3" AS (
  SELECT
    AVG(O_TOTALPRICE) AS AVG_O_TOTALPRICE
  FROM MAIN.ORDERS
  WHERE
    EXTRACT(YEAR FROM CAST(O_ORDERDATE AS DATE)) = 1996
  GROUP BY
    O_ORDERSTATUS
), "_s1" AS (
  SELECT
    MAX(AVG_O_TOTALPRICE) AS MAX_AVG_O_TOTALPRICE,
    MIN(AVG_O_TOTALPRICE) AS MIN_AVG_O_TOTALPRICE
  FROM "_t3"
)
SELECT
  "_s0".MIN_AVG_O_TOTALPRICE AS min_1995,
  "_s0".MAX_AVG_O_TOTALPRICE AS max_1995,
  "_s1".MIN_AVG_O_TOTALPRICE AS min_1996,
  "_s1".MAX_AVG_O_TOTALPRICE AS max_1996
FROM "_s0" "_s0"
CROSS JOIN "_s1" "_s1"
