WITH MONTHS AS (
  SELECT
    TO_DATE('1992-01-01', 'YYYY-MM-DD') AS DATE_VAL
  UNION ALL
  SELECT
    ADD_MONTHS(DATE_VAL, 1) AS DATE_VAL
  FROM MONTHS
  WHERE
    DATE_VAL < '1998-12-01'
), "_0" AS (
  SELECT
    DATE_VAL
  FROM MONTHS
), "_s3" AS (
  SELECT
    "_1".DATE_VAL,
    COUNT(*) AS N_ROWS
  FROM "_0" "_1"
  JOIN MAIN.ORDERS ORDERS
    ON "_1".DATE_VAL = TRUNC(CAST(ORDERS.O_ORDERDATE AS DATE), 'MONTH')
  GROUP BY
    "_1".DATE_VAL
), "_s7" AS (
  SELECT
    "_2".DATE_VAL,
    COUNT(*) AS N_ROWS
  FROM "_0" "_2"
  JOIN MAIN.LINEITEM LINEITEM
    ON "_2".DATE_VAL = TRUNC(CAST(LINEITEM.L_SHIPDATE AS DATE), 'MONTH')
  GROUP BY
    "_2".DATE_VAL
), "_s11" AS (
  SELECT
    "_3".DATE_VAL,
    COUNT(*) AS N_ROWS
  FROM "_0" "_3"
  JOIN MAIN.LINEITEM LINEITEM
    ON "_3".DATE_VAL = TRUNC(CAST(LINEITEM.L_COMMITDATE AS DATE), 'MONTH')
  GROUP BY
    "_3".DATE_VAL
), "_s15" AS (
  SELECT
    "_4".DATE_VAL,
    COUNT(*) AS N_ROWS
  FROM "_0" "_4"
  JOIN MAIN.LINEITEM LINEITEM
    ON "_4".DATE_VAL = TRUNC(CAST(LINEITEM.L_RECEIPTDATE AS DATE), 'MONTH')
  GROUP BY
    "_4".DATE_VAL
)
SELECT
  "_0".DATE_VAL AS month,
  COALESCE("_s3".N_ROWS, 0) AS orders,
  COALESCE("_s7".N_ROWS, 0) AS lines_shipped,
  COALESCE("_s11".N_ROWS, 0) AS lines_committed,
  COALESCE("_s15".N_ROWS, 0) AS lines_received
FROM "_0" "_0"
LEFT JOIN "_s3" "_s3"
  ON "_0".DATE_VAL = "_s3".DATE_VAL
LEFT JOIN "_s7" "_s7"
  ON "_0".DATE_VAL = "_s7".DATE_VAL
LEFT JOIN "_s11" "_s11"
  ON "_0".DATE_VAL = "_s11".DATE_VAL
LEFT JOIN "_s15" "_s15"
  ON "_0".DATE_VAL = "_s15".DATE_VAL
