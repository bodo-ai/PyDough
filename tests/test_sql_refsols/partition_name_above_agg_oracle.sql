WITH "_T4" AS (
  SELECT
    c_acctbal AS C_ACCTBAL,
    c_mktsegment AS C_MKTSEGMENT,
    c_nationkey AS C_NATIONKEY
  FROM TPCH.CUSTOMER
  WHERE
    c_acctbal < 0
), "_S0" AS (
  SELECT
    C_MKTSEGMENT,
    C_NATIONKEY,
    COUNT(*) AS N_ROWS
  FROM "_T4"
  GROUP BY
    C_MKTSEGMENT,
    C_NATIONKEY
), "_S1" AS (
  SELECT
    n_name AS N_NAME,
    n_nationkey AS N_NATIONKEY
  FROM TPCH.NATION
), "_S4" AS (
  SELECT
    "_S0".C_MKTSEGMENT,
    "_S1".N_NAME,
    SUM("_S0".N_ROWS) AS SUM_N_ROWS
  FROM "_S0" "_S0"
  JOIN "_S1" "_S1"
    ON "_S0".C_NATIONKEY = "_S1".N_NATIONKEY
  GROUP BY
    "_S0".C_MKTSEGMENT,
    "_S1".N_NAME
), "_S5" AS (
  SELECT
    CUSTOMER.c_mktsegment AS C_MKTSEGMENT,
    CUSTOMER.c_name AS C_NAME,
    "_S3".N_NAME,
    "_S3".N_NATIONKEY
  FROM TPCH.CUSTOMER CUSTOMER
  JOIN "_S1" "_S3"
    ON CUSTOMER.c_nationkey = "_S3".N_NATIONKEY
  WHERE
    CUSTOMER.c_acctbal < 0
), "_S7" AS (
  SELECT
    C_MKTSEGMENT,
    C_NATIONKEY
  FROM "_T4"
)
SELECT
  ANY_VALUE("_S5".N_NAME) AS n_name,
  "_S5".C_MKTSEGMENT AS c_industry,
  ANY_VALUE("_S5".C_NAME) AS c_name,
  ANY_VALUE("_S4".SUM_N_ROWS) AS n,
  COALESCE(CASE WHEN AGG_1 <> 0 THEN COUNT("_S7".C_NATIONKEY) ELSE NULL END, 0) AS n_seg
FROM "_S4" "_S4"
JOIN "_S5" "_S5"
  ON "_S4".C_MKTSEGMENT = "_S5".C_MKTSEGMENT AND "_S4".N_NAME = "_S5".N_NAME
LEFT JOIN "_S7" "_S7"
  ON "_S5".C_MKTSEGMENT = "_S7".C_MKTSEGMENT AND "_S5".N_NATIONKEY = "_S7".C_NATIONKEY
GROUP BY
  "_S5".C_MKTSEGMENT,
  "_S5".N_NATIONKEY
ORDER BY
  4 DESC NULLS LAST,
  3 NULLS FIRST
FETCH FIRST 3 ROWS ONLY
