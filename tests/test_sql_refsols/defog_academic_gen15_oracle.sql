WITH "_s2" AS (
  SELECT
    CONTINENT,
    COUNT(*) AS N_ROWS
  FROM MAIN.ORGANIZATION
  GROUP BY
    CONTINENT
), "_s3" AS (
  SELECT
    ORGANIZATION.CONTINENT,
    COUNT(*) AS N_ROWS
  FROM MAIN.ORGANIZATION ORGANIZATION
  JOIN MAIN.AUTHOR AUTHOR
    ON AUTHOR.OID = ORGANIZATION.OID
  GROUP BY
    ORGANIZATION.CONTINENT
)
SELECT
  "_s2".CONTINENT AS continent,
  COALESCE("_s3".N_ROWS, 0) / NULLIF("_s2".N_ROWS, 0) AS ratio
FROM "_s2" "_s2"
LEFT JOIN "_s3" "_s3"
  ON "_s2".CONTINENT = "_s3".CONTINENT
ORDER BY
  2 DESC NULLS LAST
