WITH "_s3" AS (
  SELECT
    TRUNC(CAST(SALES.SALE_DATE AS DATE), 'MONTH') AS SALE_MONTH,
    COUNT(*) AS N_ROWS,
    SUM(SALES.SALE_PRICE) AS SUM_SALE_PRICE
  FROM MAIN.SALES SALES
  JOIN MAIN.SALESPERSONS SALESPERSONS
    ON EXTRACT(YEAR FROM CAST(SALESPERSONS.HIRE_DATE AS DATE)) <= 2023
    AND EXTRACT(YEAR FROM CAST(SALESPERSONS.HIRE_DATE AS DATE)) >= 2022
    AND SALES.SALESPERSON_ID = SALESPERSONS."_id"
  GROUP BY
    TRUNC(CAST(SALES.SALE_DATE AS DATE), 'MONTH')
)
SELECT
  TO_CHAR(TRUNC(MONTHS_RANGE.DT, 'MONTH'), 'YYYY-MM-DD') AS month,
  COALESCE("_s3".N_ROWS, 0) AS PMSPS,
  COALESCE("_s3".SUM_SALE_PRICE, 0) AS PMSR
FROM (VALUES
  (TO_DATE('2025-10-01 00:00:00', 'YYYY-MM-DD HH24:MI:SS')),
  (TO_DATE('2025-11-01 00:00:00', 'YYYY-MM-DD HH24:MI:SS')),
  (TO_DATE('2025-12-01 00:00:00', 'YYYY-MM-DD HH24:MI:SS')),
  (TO_DATE('2026-01-01 00:00:00', 'YYYY-MM-DD HH24:MI:SS')),
  (TO_DATE('2026-02-01 00:00:00', 'YYYY-MM-DD HH24:MI:SS')),
  (TO_DATE('2026-03-01 00:00:00', 'YYYY-MM-DD HH24:MI:SS'))) AS MONTHS_RANGE(DT)
LEFT JOIN "_s3" "_s3"
  ON "_s3".SALE_MONTH = TRUNC(MONTHS_RANGE.DT, 'MONTH')
ORDER BY
  TRUNC(MONTHS_RANGE.DT, 'MONTH') NULLS FIRST
