WITH DATE_RANGE AS (
  SELECT
    ADD_MONTHS(TO_DATE('1992-01-01', 'YYYY-MM-DD'), LEVEL - 1) AS DATE_VAL
  FROM DUAL
  CONNECT BY LEVEL <= 84
), "_0" AS (
  SELECT
    DATE_VAL
  FROM DATE_RANGE
), "_s2" AS (
  SELECT
    DATE_VAL
  FROM "_0"
  ORDER BY
    1 NULLS FIRST
  FETCH FIRST 5 ROWS ONLY
), "_s0" AS (
  SELECT
    DATE_VAL
  FROM "_0"
  ORDER BY
    1 NULLS FIRST
  FETCH FIRST 5 ROWS ONLY
), "_s3" AS (
  SELECT
    "_s0".DATE_VAL,
    COUNT(*) AS N_ROWS
  FROM "_s0" "_s0"
  JOIN TPCH.ORDERS ORDERS
    ON "_s0".DATE_VAL = TRUNC(CAST(ORDERS.O_ORDERDATE AS DATE), 'MONTH')
  GROUP BY
    "_s0".DATE_VAL
), "_s4" AS (
  SELECT
    DATE_VAL
  FROM "_0"
  ORDER BY
    1 NULLS FIRST
  FETCH FIRST 5 ROWS ONLY
), "_s7" AS (
  SELECT
    "_s4".DATE_VAL,
    COUNT(*) AS N_ROWS
  FROM "_s4" "_s4"
  JOIN TPCH.LINEITEM LINEITEM
    ON "_s4".DATE_VAL = TRUNC(CAST(LINEITEM.L_SHIPDATE AS DATE), 'MONTH')
  GROUP BY
    "_s4".DATE_VAL
), "_s8" AS (
  SELECT
    DATE_VAL
  FROM "_0"
  ORDER BY
    1 NULLS FIRST
  FETCH FIRST 5 ROWS ONLY
), "_s11" AS (
  SELECT
    "_s8".DATE_VAL,
    COUNT(*) AS N_ROWS
  FROM "_s8" "_s8"
  JOIN TPCH.LINEITEM LINEITEM
    ON "_s8".DATE_VAL = TRUNC(CAST(LINEITEM.L_COMMITDATE AS DATE), 'MONTH')
  GROUP BY
    "_s8".DATE_VAL
), "_s12" AS (
  SELECT
    DATE_VAL
  FROM "_0"
  ORDER BY
    1 NULLS FIRST
  FETCH FIRST 5 ROWS ONLY
), "_s15" AS (
  SELECT
    "_s12".DATE_VAL,
    COUNT(*) AS N_ROWS
  FROM "_s12" "_s12"
  JOIN TPCH.LINEITEM LINEITEM
    ON "_s12".DATE_VAL = TRUNC(CAST(LINEITEM.L_RECEIPTDATE AS DATE), 'MONTH')
  GROUP BY
    "_s12".DATE_VAL
)
SELECT
  "_s2".DATE_VAL AS month,
  COALESCE("_s3".N_ROWS, 0) AS orders,
  COALESCE("_s7".N_ROWS, 0) AS lines_shipped,
  COALESCE("_s11".N_ROWS, 0) AS lines_committed,
  COALESCE("_s15".N_ROWS, 0) AS lines_received
FROM "_s2" "_s2"
LEFT JOIN "_s3" "_s3"
  ON "_s2".DATE_VAL = "_s3".DATE_VAL
LEFT JOIN "_s7" "_s7"
  ON "_s2".DATE_VAL = "_s7".DATE_VAL
LEFT JOIN "_s11" "_s11"
  ON "_s11".DATE_VAL = "_s2".DATE_VAL
LEFT JOIN "_s15" "_s15"
  ON "_s15".DATE_VAL = "_s2".DATE_VAL
ORDER BY
  1 NULLS FIRST
