WITH "_T1" AS (
  SELECT
    pr_name AS PR_NAME
  FROM MAIN.PRODUCTS
  WHERE
    pr_name = 'RubyCopper-Star'
), "_T2" AS (
  SELECT
    co_name AS CO_NAME
  FROM MAIN.COUNTRIES
  WHERE
    co_name = 'CN'
), "_T4" AS (
  SELECT
    PR_NAME,
    PR_RELEASE
  FROM MAIN.PRODUCTS
  WHERE
    pr_name = 'RubyCopper-Star'
), "_S5" AS (
  SELECT
    CA_DT
  FROM MAIN.CALENDAR
), "_S13" AS (
  SELECT
    "_S9".CA_DT,
    COUNT(*) AS N_ROWS
  FROM "_T4" "_T7"
  CROSS JOIN "_T2" "_T8"
  JOIN "_S5" "_S9"
    ON "_S9".CA_DT < TRUNC(ADD_MONTHS(CAST("_T7".PR_RELEASE AS DATE), 24), 'Q')
    AND "_S9".CA_DT >= "_T7".PR_RELEASE
  JOIN MAIN.DEVICES DEVICES
    ON DEVICES.de_product_id = 800544
    AND "_S9".CA_DT = TRUNC(CAST(CAST(DEVICES.de_purchase_ts AS DATE) AS DATE), 'DD')
  GROUP BY
    "_S9".CA_DT
), "_S15" AS (
  SELECT
    TRUNC(CAST(CAST("_S5".CA_DT AS DATE) AS DATE), 'Q') AS QUARTER,
    SUM("_S13".N_ROWS) AS SUM_N_ROWS
  FROM "_T4" "_T4"
  CROSS JOIN "_T2" "_T5"
  JOIN "_S5" "_S5"
    ON "_S5".CA_DT < TRUNC(ADD_MONTHS(CAST("_T4".PR_RELEASE AS DATE), 24), 'Q')
    AND "_S5".CA_DT >= "_T4".PR_RELEASE
  LEFT JOIN "_S13" "_S13"
    ON "_S13".CA_DT = "_S5".CA_DT
  GROUP BY
    TRUNC(CAST(CAST("_S5".CA_DT AS DATE) AS DATE), 'Q')
), "_S23" AS (
  SELECT DISTINCT
    TRUNC(CAST(CAST("_S21".CA_DT AS DATE) AS DATE), 'Q') AS QUARTER
  FROM "_T4" "_T14"
  CROSS JOIN "_T2" "_T15"
  JOIN "_S5" "_S21"
    ON "_S21".CA_DT < TRUNC(ADD_MONTHS(CAST("_T14".PR_RELEASE AS DATE), 24), 'Q')
    AND "_S21".CA_DT >= "_T14".PR_RELEASE
), "_S29" AS (
  SELECT
    "_S27".CA_DT
  FROM "_T4" "_T16"
  CROSS JOIN "_T2" "_T17"
  JOIN "_S5" "_S27"
    ON "_S27".CA_DT < TRUNC(ADD_MONTHS(CAST("_T16".PR_RELEASE AS DATE), 24), 'Q')
    AND "_S27".CA_DT >= "_T16".PR_RELEASE
), "_S35" AS (
  SELECT
    "_S23".QUARTER,
    COUNT(DISTINCT INCIDENTS.in_device_id) AS NDISTINCT_IN_DEVICE_ID
  FROM "_T1" "_T11"
  JOIN MAIN.COUNTRIES COUNTRIES
    ON COUNTRIES.co_name = 'CN'
  CROSS JOIN "_S23" "_S23"
  JOIN "_S29" "_S29"
    ON "_S23".QUARTER = TRUNC(CAST(CAST("_S29".CA_DT AS DATE) AS DATE), 'Q')
  JOIN MAIN.INCIDENTS INCIDENTS
    ON COUNTRIES.co_id = INCIDENTS.in_repair_country_id
    AND "_S29".CA_DT = TRUNC(CAST(CAST(INCIDENTS.in_error_report_ts AS DATE) AS DATE), 'DD')
  JOIN MAIN.DEVICES DEVICES
    ON DEVICES.de_id = INCIDENTS.in_device_id AND DEVICES.de_product_id = 800544
  GROUP BY
    "_S23".QUARTER
)
SELECT
  "_S15".QUARTER AS quarter,
  COALESCE("_S35".NDISTINCT_IN_DEVICE_ID, 0) AS n_incidents,
  COALESCE("_S15".SUM_N_ROWS, 0) AS n_sold,
  ROUND(
    SUM(COALESCE("_S35".NDISTINCT_IN_DEVICE_ID, 0)) OVER (ORDER BY "_S15".QUARTER ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) / SUM(COALESCE("_S15".SUM_N_ROWS, 0)) OVER (ORDER BY "_S15".QUARTER ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW),
    2
  ) AS quarter_cum
FROM "_T1" "_T1"
CROSS JOIN "_T2" "_T2"
CROSS JOIN "_S15" "_S15"
LEFT JOIN "_S35" "_S35"
  ON "_S15".QUARTER = "_S35".QUARTER
ORDER BY
  1 NULLS FIRST
