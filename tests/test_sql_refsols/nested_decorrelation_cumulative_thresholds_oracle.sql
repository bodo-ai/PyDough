WITH "_t1" AS (
  SELECT
    N_NATIONKEY
  FROM TPCH.NATION
  WHERE
    N_NATIONKEY <= 4
), "_t5" AS (
  SELECT
    R_REGIONKEY
  FROM TPCH.REGION
  WHERE
    R_REGIONKEY <= 2
), "_s7" AS (
  SELECT
    L_ORDERKEY,
    SUM(L_EXTENDEDPRICE) AS SUM_L_EXTENDEDPRICE
  FROM TPCH.LINEITEM
  GROUP BY
    L_ORDERKEY
), "_s9" AS (
  SELECT
    COALESCE(SUM("_s7".SUM_L_EXTENDEDPRICE), 0) AS SUM_ORDER_VALUE,
    "_t8".N_NATIONKEY,
    "_t9".R_REGIONKEY
  FROM "_t1" "_t8"
  CROSS JOIN "_t5" "_t9"
  JOIN TPCH.ORDERS ORDERS
    ON ORDERS.O_ORDERKEY <= "_t9".R_REGIONKEY AND ORDERS.O_ORDERKEY = 1
  JOIN "_s7" "_s7"
    ON ORDERS.O_ORDERKEY = "_s7".L_ORDERKEY
  GROUP BY
    "_t8".N_NATIONKEY,
    "_t9".R_REGIONKEY
), "_s11" AS (
  SELECT
    COALESCE(SUM("_s9".SUM_ORDER_VALUE), 0) AS SUM_AMOUNT,
    "_t4".N_NATIONKEY
  FROM "_t1" "_t4"
  JOIN "_t5" "_t5"
    ON "_t4".N_NATIONKEY >= "_t5".R_REGIONKEY
  LEFT JOIN "_s9" "_s9"
    ON "_s9".N_NATIONKEY = "_t4".N_NATIONKEY AND "_s9".R_REGIONKEY = "_t5".R_REGIONKEY
  GROUP BY
    "_t4".N_NATIONKEY
)
SELECT
  "_t1".N_NATIONKEY AS k,
  COALESCE("_s11".SUM_AMOUNT, 0) AS total_value
FROM "_t1" "_t1"
LEFT JOIN "_s11" "_s11"
  ON "_s11".N_NATIONKEY = "_t1".N_NATIONKEY
ORDER BY
  1 NULLS FIRST
