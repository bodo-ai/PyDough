WITH "_T1" AS (
  SELECT
    pr_name AS PR_NAME
  FROM MAIN.PRODUCTS
  WHERE
    pr_name = 'RubyCopper-Star'
), "_T2" AS (
  SELECT
    co_name AS CO_NAME
  FROM MAIN.COUNTRIES
  WHERE
    co_name = 'CN'
), "_T4" AS (
  SELECT
    pr_name AS PR_NAME,
    pr_release AS PR_RELEASE
  FROM MAIN.PRODUCTS
  WHERE
    pr_name = 'RubyCopper-Star'
), "_S5" AS (
  SELECT
    ca_dt AS CA_DT
  FROM MAIN.CALENDAR
), "_S7" AS (
  SELECT DISTINCT
    TRUNC(CAST(CAST("_S5".CA_DT AS DATE) AS DATE), 'Q') AS QUARTER
  FROM "_T4" "_T4"
  CROSS JOIN "_T2" "_T5"
  JOIN "_S5" "_S5"
    ON "_S5".CA_DT < TRUNC(ADD_MONTHS(CAST("_T4".PR_RELEASE AS DATE), 24), 'Q')
    AND "_S5".CA_DT >= "_T4".PR_RELEASE
), "_S15" AS (
  SELECT DISTINCT
    TRUNC(CAST(CAST("_S13".CA_DT AS DATE) AS DATE), 'Q') AS QUARTER
  FROM "_T4" "_T10"
  CROSS JOIN "_T2" "_T11"
  JOIN "_S5" "_S13"
    ON "_S13".CA_DT < TRUNC(ADD_MONTHS(CAST("_T10".PR_RELEASE AS DATE), 24), 'Q')
    AND "_S13".CA_DT >= "_T10".PR_RELEASE
), "_S21" AS (
  SELECT
    "_S19".CA_DT
  FROM "_T4" "_T12"
  CROSS JOIN "_T2" "_T13"
  JOIN "_S5" "_S19"
    ON "_S19".CA_DT < TRUNC(ADD_MONTHS(CAST("_T12".PR_RELEASE AS DATE), 24), 'Q')
    AND "_S19".CA_DT >= "_T12".PR_RELEASE
), "_S27" AS (
  SELECT
    "_S15".QUARTER,
    COUNT(DISTINCT INCIDENTS.in_device_id) AS NDISTINCT_IN_DEVICE_ID
  FROM "_T1" "_T7"
  JOIN MAIN.COUNTRIES COUNTRIES
    ON COUNTRIES.co_name = 'CN'
  CROSS JOIN "_S15" "_S15"
  JOIN "_S21" "_S21"
    ON "_S15".QUARTER = TRUNC(CAST(CAST("_S21".CA_DT AS DATE) AS DATE), 'Q')
  JOIN MAIN.INCIDENTS INCIDENTS
    ON COUNTRIES.co_id = INCIDENTS.in_repair_country_id
    AND "_S21".CA_DT = TRUNC(CAST(CAST(INCIDENTS.in_error_report_ts AS DATE) AS DATE), 'DD')
  JOIN MAIN.DEVICES DEVICES
    ON DEVICES.de_id = INCIDENTS.in_device_id AND DEVICES.de_product_id = 800544
  GROUP BY
    "_S15".QUARTER
), "_S35" AS (
  SELECT
    TRUNC(CAST(CAST("_S31".CA_DT AS DATE) AS DATE), 'Q') AS QUARTER,
    COUNT(*) AS N_ROWS
  FROM "_T4" "_T16"
  CROSS JOIN "_T2" "_T17"
  JOIN "_S5" "_S31"
    ON "_S31".CA_DT < TRUNC(ADD_MONTHS(CAST("_T16".PR_RELEASE AS DATE), 24), 'Q')
    AND "_S31".CA_DT >= "_T16".PR_RELEASE
  JOIN MAIN.DEVICES DEVICES
    ON DEVICES.de_product_id = 800544
    AND "_S31".CA_DT = TRUNC(CAST(CAST(DEVICES.de_purchase_ts AS DATE) AS DATE), 'DD')
  GROUP BY
    TRUNC(CAST(CAST("_S31".CA_DT AS DATE) AS DATE), 'Q')
)
SELECT
  "_S7".QUARTER AS quarter,
  COALESCE("_S27".NDISTINCT_IN_DEVICE_ID, 0) AS n_incidents,
  COALESCE("_S35".N_ROWS, 0) AS n_sold,
  ROUND(
    SUM(COALESCE("_S27".NDISTINCT_IN_DEVICE_ID, 0)) OVER (ORDER BY "_S7".QUARTER ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) / SUM(COALESCE("_S35".N_ROWS, 0)) OVER (ORDER BY "_S7".QUARTER ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW),
    2
  ) AS quarter_cum
FROM "_T1" "_T1"
CROSS JOIN "_T2" "_T2"
CROSS JOIN "_S7" "_S7"
LEFT JOIN "_S27" "_S27"
  ON "_S27".QUARTER = "_S7".QUARTER
LEFT JOIN "_S35" "_S35"
  ON "_S35".QUARTER = "_S7".QUARTER
ORDER BY
  1 NULLS FIRST
