WITH "_s2" AS (
  SELECT DISTINCT
    MAKE,
    MODEL
  FROM MAIN.CARS
  WHERE
    LOWER(VIN_NUMBER) LIKE '%m5%'
), "_s3" AS (
  SELECT
    CARS.MAKE,
    CARS.MODEL,
    COUNT(*) AS N_ROWS
  FROM MAIN.CARS CARS
  JOIN MAIN.SALES SALES
    ON CARS."_id" = SALES.CAR_ID
  WHERE
    LOWER(CARS.VIN_NUMBER) LIKE '%m5%'
  GROUP BY
    CARS.MAKE,
    CARS.MODEL
)
SELECT
  "_s2".MAKE AS make,
  "_s2".MODEL AS model,
  COALESCE("_s3".N_ROWS, 0) AS num_sales
FROM "_s2" "_s2"
LEFT JOIN "_s3" "_s3"
  ON "_s2".MAKE = "_s3".MAKE AND "_s2".MODEL = "_s3".MODEL
