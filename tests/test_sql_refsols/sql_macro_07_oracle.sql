WITH "_0" AS (
  SELECT DISTINCT
    REGEXP_SUBSTR(P.P_NAME, '[^ ]+', 1, L.LVL) AS COLOR
  FROM PART P
  CROSS JOIN LATERAL (
    SELECT
      "LEVEL" AS LVL
    FROM DUAL
    CONNECT BY "LEVEL" <= REGEXP_COUNT(P.P_NAME, '[^ ]+')
  ) AS L
)
SELECT
  COLOR AS color
FROM "_0"
ORDER BY
  1 NULLS FIRST
FETCH FIRST 5 ROWS ONLY
