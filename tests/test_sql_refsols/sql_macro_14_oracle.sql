WITH RECURSIVE MONTHS AS (
  SELECT
    TO_DATE('1992-01-01', 'YYYY-MM-DD') AS DATE_VAL,
    1992 AS YR,
    1 AS MO
  UNION ALL
  SELECT
    ADD_MONTHS(DATE_VAL, 1) AS DATE_VAL,
    EXTRACT(YEAR FROM CAST(ADD_MONTHS(DATE_VAL, 1) AS DATE)) AS YR,
    EXTRACT(MONTH FROM CAST(ADD_MONTHS(DATE_VAL, 1) AS DATE)) AS MO
  FROM MONTHS
  WHERE
    DATE_VAL < CAST('1998-12-01' AS DATE)
), "_s2" AS (
  SELECT
    DATE_VAL,
    MO,
    YR
  FROM MONTHS
  ORDER BY
    1 NULLS FIRST
  FETCH FIRST 24 ROWS ONLY
), "_s0" AS (
  SELECT
    DATE_VAL,
    YR
  FROM MONTHS
  ORDER BY
    1 NULLS FIRST
  FETCH FIRST 24 ROWS ONLY
), "_s3" AS (
  SELECT
    "_s0".DATE_VAL,
    "_s0".YR,
    COUNT(*) AS N_ROWS
  FROM "_s0" "_s0"
  JOIN TPCH.ORDERS ORDERS
    ON "_s0".DATE_VAL = TRUNC(CAST(ORDERS.O_ORDERDATE AS DATE), 'MONTH')
  GROUP BY
    "_s0".DATE_VAL,
    "_s0".YR
)
SELECT
  "_s2".YR AS year,
  "_s2".MO AS month_of_year,
  SUM(COALESCE("_s3".N_ROWS, 0)) OVER (
    PARTITION BY "_s2".YR
    ORDER BY "_s2".MO
    ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
  ) AS csum,
  COALESCE("_s3".N_ROWS, 0) - LAG(COALESCE("_s3".N_ROWS, 0), 1) OVER (PARTITION BY "_s2".YR ORDER BY "_s2".MO) AS delta
FROM "_s2" "_s2"
LEFT JOIN "_s3" "_s3"
  ON "_s2".DATE_VAL = "_s3".DATE_VAL AND "_s2".YR = "_s3".YR
ORDER BY
  1 NULLS FIRST,
  2 NULLS FIRST
