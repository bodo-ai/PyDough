WITH "_s2" AS (
  SELECT
    CA_DT
  FROM MAIN.CALENDAR
), "_s3" AS (
  SELECT
    EXTRACT(YEAR FROM CAST("_s0".CA_DT AS DATE)) AS YEAR_CA_DT,
    COUNT(*) AS N_ROWS
  FROM "_s2" "_s0"
  JOIN MAIN.DEVICES DEVICES
    ON "_s0".CA_DT = TRUNC(CAST(CAST(DEVICES.DE_PURCHASE_TS AS DATE) AS DATE), 'DD')
  GROUP BY
    EXTRACT(YEAR FROM CAST("_s0".CA_DT AS DATE))
), "_s6" AS (
  SELECT
    EXTRACT(YEAR FROM CAST("_s2".CA_DT AS DATE)) AS YEAR_CA_DT,
    ANY_VALUE("_s3".N_ROWS) AS ANYTHING_N_ROWS
  FROM "_s2" "_s2"
  JOIN "_s3" "_s3"
    ON "_s3".YEAR_CA_DT = EXTRACT(YEAR FROM CAST("_s2".CA_DT AS DATE))
  GROUP BY
    EXTRACT(YEAR FROM CAST("_s2".CA_DT AS DATE))
), "_s7" AS (
  SELECT
    EXTRACT(YEAR FROM CAST("_s4".CA_DT AS DATE)) AS YEAR_CA_DT,
    COUNT(*) AS N_ROWS
  FROM "_s2" "_s4"
  JOIN MAIN.INCIDENTS INCIDENTS
    ON "_s4".CA_DT = TRUNC(CAST(CAST(INCIDENTS.IN_ERROR_REPORT_TS AS DATE) AS DATE), 'DD')
  GROUP BY
    EXTRACT(YEAR FROM CAST("_s4".CA_DT AS DATE))
)
SELECT
  "_s6".YEAR_CA_DT AS yr,
  ROUND(
    SUM(COALESCE("_s7".N_ROWS, 0)) OVER (ORDER BY "_s6".YEAR_CA_DT ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) / SUM(COALESCE("_s6".ANYTHING_N_ROWS, 0)) OVER (ORDER BY "_s6".YEAR_CA_DT ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW),
    2
  ) AS cum_ir,
  ROUND(
    (
      100.0 * (
        COALESCE("_s6".ANYTHING_N_ROWS, 0) - LAG(COALESCE("_s6".ANYTHING_N_ROWS, 0), 1) OVER (ORDER BY "_s6".YEAR_CA_DT)
      )
    ) / LAG(COALESCE("_s6".ANYTHING_N_ROWS, 0), 1) OVER (ORDER BY "_s6".YEAR_CA_DT),
    2
  ) AS pct_bought_change,
  ROUND(
    (
      100.0 * (
        COALESCE("_s7".N_ROWS, 0) - LAG(COALESCE("_s7".N_ROWS, 0), 1) OVER (ORDER BY "_s6".YEAR_CA_DT)
      )
    ) / LAG(COALESCE("_s7".N_ROWS, 0), 1) OVER (ORDER BY "_s6".YEAR_CA_DT),
    2
  ) AS pct_incident_change,
  COALESCE("_s6".ANYTHING_N_ROWS, 0) AS bought,
  COALESCE("_s7".N_ROWS, 0) AS incidents
FROM "_s6" "_s6"
LEFT JOIN "_s7" "_s7"
  ON "_s6".YEAR_CA_DT = "_s7".YEAR_CA_DT
ORDER BY
  1 NULLS FIRST
