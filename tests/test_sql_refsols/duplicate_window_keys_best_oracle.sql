WITH "_t" AS (
  SELECT
    O_CUSTKEY,
    O_ORDERKEY,
    ROW_NUMBER() OVER (PARTITION BY O_CUSTKEY ORDER BY O_TOTALPRICE DESC, O_ORDERKEY) AS "_w"
  FROM TPCH.ORDERS
), "_s1" AS (
  SELECT
    O_CUSTKEY,
    O_ORDERKEY
  FROM "_t"
  WHERE
    "_w" = 1
)
SELECT
  CUSTOMER.C_CUSTKEY AS "key",
  "_s1".O_ORDERKEY AS best_order
FROM TPCH.CUSTOMER CUSTOMER
LEFT JOIN "_s1" "_s1"
  ON CUSTOMER.C_CUSTKEY = "_s1".O_CUSTKEY
WHERE
  CUSTOMER.C_CUSTKEY <= 3
ORDER BY
  1 NULLS FIRST
