WITH "_s2" AS (
  SELECT
    C_NATIONKEY,
    COUNT(*) AS N_ROWS
  FROM TPCH.CUSTOMER
  GROUP BY
    C_NATIONKEY
)
SELECT
  NVL(NATION.N_NAME, '') || ' - ' || NVL(REGION.R_NAME, '') AS label,
  SUM("_s2".N_ROWS) AS n_customers
FROM "_s2" "_s2"
JOIN TPCH.NATION NATION
  ON NATION.N_NATIONKEY = "_s2".C_NATIONKEY
JOIN TPCH.REGION REGION
  ON NATION.N_REGIONKEY = REGION.R_REGIONKEY
GROUP BY
  NVL(NATION.N_NAME, '') || ' - ' || NVL(REGION.R_NAME, '')
ORDER BY
  1 NULLS FIRST
