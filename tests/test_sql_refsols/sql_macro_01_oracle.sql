WITH "_0" AS (
  SELECT
    '1-URGENT' AS PRIORITY_NAME,
    1 AS PRIORITY_VALUE
  UNION ALL
  SELECT
    '2-HIGH' AS "2-HIGH",
    2 AS "2"
  UNION ALL
  SELECT
    '3-MEDIUM' AS "3-MEDIUM",
    3 AS "3"
  UNION ALL
  SELECT
    '4-NOT SPECIFIED' AS "4-NOT SPECIFIED",
    4 AS "4"
  UNION ALL
  SELECT
    '5-LOW' AS "5-LOW",
    5 AS "5"
)
SELECT
  PRIORITY_NAME AS name,
  PRIORITY_VALUE AS value
FROM "_0"
