WITH "_S2" AS (
  SELECT DISTINCT
    sbcustcountry AS SBCUSTCOUNTRY
  FROM MAIN.SBCUSTOMER
), "_S1" AS (
  SELECT
    sbtxcustid AS SBTXCUSTID,
    COUNT(*) AS N_ROWS,
    SUM(sbtxamount) AS SUM_SBTXAMOUNT
  FROM MAIN.SBTRANSACTION
  WHERE
    sbtxdatetime >= TRUNC(SYS_EXTRACT_UTC(SYSTIMESTAMP) - NUMTODSINTERVAL(30, 'day'), 'DD')
  GROUP BY
    sbtxcustid
), "_S3" AS (
  SELECT
    SBCUSTOMER.sbcustcountry AS SBCUSTCOUNTRY,
    SUM("_S1".N_ROWS) AS SUM_N_ROWS,
    SUM("_S1".SUM_SBTXAMOUNT) AS SUM_SUM_SBTXAMOUNT
  FROM MAIN.SBCUSTOMER SBCUSTOMER
  JOIN "_S1" "_S1"
    ON SBCUSTOMER.sbcustid = "_S1".SBTXCUSTID
  GROUP BY
    SBCUSTOMER.sbcustcountry
)
SELECT
  "_S2".SBCUSTCOUNTRY AS country,
  COALESCE("_S3".SUM_N_ROWS, 0) AS num_transactions,
  COALESCE("_S3".SUM_SUM_SBTXAMOUNT, 0) AS total_amount
FROM "_S2" "_S2"
LEFT JOIN "_S3" "_S3"
  ON "_S2".SBCUSTCOUNTRY = "_S3".SBCUSTCOUNTRY
