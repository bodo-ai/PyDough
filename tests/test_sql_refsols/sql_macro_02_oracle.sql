WITH "_0" AS (
  SELECT
    '1-URGENT' AS PRIORITY_NAME,
    1 AS PRIORITY_VALUE
  UNION ALL
  SELECT
    '2-HIGH' AS "2-HIGH",
    2 AS "2"
  UNION ALL
  SELECT
    '3-MEDIUM' AS "3-MEDIUM",
    3 AS "3"
  UNION ALL
  SELECT
    '4-NOT SPECIFIED' AS "4-NOT SPECIFIED",
    4 AS "4"
  UNION ALL
  SELECT
    '5-LOW' AS "5-LOW",
    5 AS "5"
), "_s0" AS (
  SELECT
    PRIORITY_NAME,
    PRIORITY_VALUE
  FROM "_0"
  ORDER BY
    2 NULLS FIRST
  FETCH FIRST 3 ROWS ONLY
)
SELECT
  ORDERS.O_ORDERPRIORITY AS name,
  COUNT(*) AS n_orders
FROM "_s0" "_s0"
JOIN MAIN.ORDERS ORDERS
  ON ORDERS.O_ORDERPRIORITY = "_s0".PRIORITY_NAME
GROUP BY
  ORDERS.O_ORDERPRIORITY
ORDER BY
  ANY_VALUE("_s0".PRIORITY_VALUE) NULLS FIRST
