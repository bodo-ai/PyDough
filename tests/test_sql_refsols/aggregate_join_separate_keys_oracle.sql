WITH "_s0" AS (
  SELECT
    C_MKTSEGMENT,
    C_NATIONKEY,
    COUNT(*) AS N_ROWS
  FROM TPCH.CUSTOMER
  GROUP BY
    C_MKTSEGMENT,
    C_NATIONKEY
)
SELECT
  "_s0".C_MKTSEGMENT AS market_segment,
  NATION.N_NAME AS nation_name,
  SUM("_s0".N_ROWS) AS n
FROM "_s0" "_s0"
JOIN TPCH.NATION NATION
  ON NATION.N_NATIONKEY = "_s0".C_NATIONKEY
GROUP BY
  "_s0".C_MKTSEGMENT,
  NATION.N_NAME
ORDER BY
  1 NULLS FIRST,
  2 NULLS FIRST
