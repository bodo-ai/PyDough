WITH "_s1" AS (
  SELECT
    N_REGIONKEY,
    COUNT(*) AS N_ROWS
  FROM TPCH.NATION
  WHERE
    SUBSTR(N_NAME, 1, 1) IN ('A', 'B', 'C')
  GROUP BY
    N_REGIONKEY
)
SELECT
  REGION.R_NAME AS region_name,
  'foo' AS x,
  COALESCE("_s1".N_ROWS, 0) AS n
FROM TPCH.REGION REGION
LEFT JOIN "_s1" "_s1"
  ON REGION.R_REGIONKEY = "_s1".N_REGIONKEY
ORDER BY
  1 NULLS FIRST
