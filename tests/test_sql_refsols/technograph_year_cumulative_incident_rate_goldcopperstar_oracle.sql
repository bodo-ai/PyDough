WITH "_S0" AS (
  SELECT
    ANY_VALUE(pr_release) AS ANYTHING_PR_RELEASE
  FROM MAIN.PRODUCTS
  WHERE
    pr_name = 'GoldCopper-Star'
), "_T3" AS (
  SELECT
    ca_dt AS CA_DT
  FROM MAIN.CALENDAR
), "_S1" AS (
  SELECT DISTINCT
    EXTRACT(YEAR FROM CAST(CA_DT AS DATE)) AS YEAR_CA_DT
  FROM "_T3"
), "_T5" AS (
  SELECT
    pr_id AS PR_ID,
    pr_name AS PR_NAME
  FROM MAIN.PRODUCTS
  WHERE
    pr_name = 'GoldCopper-Star'
), "_S7" AS (
  SELECT
    EXTRACT(YEAR FROM CAST("_S2".CA_DT AS DATE)) AS YEAR_CA_DT,
    COUNT(*) AS N_ROWS
  FROM "_T3" "_S2"
  JOIN MAIN.DEVICES DEVICES
    ON "_S2".CA_DT = TRUNC(CAST(CAST(DEVICES.de_purchase_ts AS DATE) AS DATE), 'DD')
  JOIN "_T5" "_T5"
    ON DEVICES.de_product_id = "_T5".PR_ID
  GROUP BY
    EXTRACT(YEAR FROM CAST("_S2".CA_DT AS DATE))
), "_S15" AS (
  SELECT
    EXTRACT(YEAR FROM CAST("_S8".CA_DT AS DATE)) AS YEAR_CA_DT,
    COUNT(*) AS N_ROWS
  FROM "_T3" "_S8"
  JOIN MAIN.INCIDENTS INCIDENTS
    ON "_S8".CA_DT = TRUNC(CAST(CAST(INCIDENTS.in_error_report_ts AS DATE) AS DATE), 'DD')
  JOIN MAIN.DEVICES DEVICES
    ON DEVICES.de_id = INCIDENTS.in_device_id
  JOIN "_T5" "_T7"
    ON DEVICES.de_product_id = "_T7".PR_ID
  GROUP BY
    EXTRACT(YEAR FROM CAST("_S8".CA_DT AS DATE))
)
SELECT
  "_S1".YEAR_CA_DT - EXTRACT(YEAR FROM CAST("_S0".ANYTHING_PR_RELEASE AS DATE)) AS years_since_release,
  ROUND(
    SUM(COALESCE("_S15".N_ROWS, 0)) OVER (ORDER BY "_S1".YEAR_CA_DT ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) / SUM(COALESCE("_S7".N_ROWS, 0)) OVER (ORDER BY "_S1".YEAR_CA_DT ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW),
    2
  ) AS cum_ir,
  ROUND(
    (
      100.0 * (
        COALESCE("_S7".N_ROWS, 0) - LAG(COALESCE("_S7".N_ROWS, 0), 1) OVER (ORDER BY "_S1".YEAR_CA_DT)
      )
    ) / LAG(COALESCE("_S7".N_ROWS, 0), 1) OVER (ORDER BY "_S1".YEAR_CA_DT),
    2
  ) AS pct_bought_change,
  ROUND(
    (
      100.0 * (
        COALESCE("_S15".N_ROWS, 0) - LAG(COALESCE("_S15".N_ROWS, 0), 1) OVER (ORDER BY "_S1".YEAR_CA_DT)
      )
    ) / LAG(COALESCE("_S15".N_ROWS, 0), 1) OVER (ORDER BY "_S1".YEAR_CA_DT),
    2
  ) AS pct_incident_change,
  COALESCE("_S7".N_ROWS, 0) AS bought,
  COALESCE("_S15".N_ROWS, 0) AS incidents
FROM "_S0" "_S0"
JOIN "_S1" "_S1"
  ON "_S1".YEAR_CA_DT >= EXTRACT(YEAR FROM CAST("_S0".ANYTHING_PR_RELEASE AS DATE))
LEFT JOIN "_S7" "_S7"
  ON "_S1".YEAR_CA_DT = "_S7".YEAR_CA_DT
LEFT JOIN "_S15" "_S15"
  ON "_S1".YEAR_CA_DT = "_S15".YEAR_CA_DT
ORDER BY
  1 NULLS FIRST
