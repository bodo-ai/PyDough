WITH "_s0" AS (
  SELECT
    C_MKTSEGMENT,
    C_NATIONKEY,
    COUNT(*) AS N_ROWS
  FROM TPCH.CUSTOMER
  GROUP BY
    C_MKTSEGMENT,
    C_NATIONKEY
), "_s4" AS (
  SELECT
    "_s0".C_MKTSEGMENT,
    NATION.N_NAME,
    SUM("_s0".N_ROWS) AS SUM_N_ROWS
  FROM "_s0" "_s0"
  JOIN TPCH.NATION NATION
    ON NATION.N_NATIONKEY = "_s0".C_NATIONKEY
  GROUP BY
    "_s0".C_MKTSEGMENT,
    NATION.N_NAME
), "_s5" AS (
  SELECT
    CUSTOMER.C_MKTSEGMENT,
    CUSTOMER.C_NAME,
    NATION.N_NAME,
    NATION.N_REGIONKEY
  FROM TPCH.CUSTOMER CUSTOMER
  JOIN TPCH.NATION NATION
    ON CUSTOMER.C_NATIONKEY = NATION.N_NATIONKEY
)
SELECT
  REGION.R_NAME AS r_name,
  "_s5".N_NAME AS n_name,
  "_s5".C_MKTSEGMENT AS c_industry,
  "_s5".C_NAME AS c_name,
  "_s4".SUM_N_ROWS AS n
FROM "_s4" "_s4"
JOIN "_s5" "_s5"
  ON "_s4".C_MKTSEGMENT = "_s5".C_MKTSEGMENT AND "_s4".N_NAME = "_s5".N_NAME
JOIN TPCH.REGION REGION
  ON REGION.R_REGIONKEY = "_s5".N_REGIONKEY
ORDER BY
  5 DESC NULLS LAST,
  4 NULLS FIRST
FETCH FIRST 3 ROWS ONLY
