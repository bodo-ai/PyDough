WITH "_s3" AS (
  SELECT
    L_ORDERKEY,
    SUM(L_EXTENDEDPRICE) AS SUM_L_EXTENDEDPRICE
  FROM TPCH.LINEITEM
  GROUP BY
    L_ORDERKEY
), "_s5" AS (
  SELECT
    COALESCE(SUM("_s3".SUM_L_EXTENDEDPRICE), 0) AS SUM_ORDER_TOTAL,
    YEARS_2.Y
  FROM (VALUES
    (1992),
    (1993),
    (1994),
    (1995),
    (1996),
    (1997),
    (1998)) AS YEARS_2(Y)
  JOIN TPCH.ORDERS ORDERS
    ON ORDERS.O_CUSTKEY = 1
    AND YEARS_2.Y >= EXTRACT(YEAR FROM CAST(ORDERS.O_ORDERDATE AS DATE))
  JOIN "_s3" "_s3"
    ON ORDERS.O_ORDERKEY = "_s3".L_ORDERKEY
  GROUP BY
    YEARS_2.Y
)
SELECT
  YEARS.Y AS yy,
  COALESCE("_s5".SUM_ORDER_TOTAL, 0) AS total_to_date
FROM (VALUES
  (1992),
  (1993),
  (1994),
  (1995),
  (1996),
  (1997),
  (1998)) AS YEARS(Y)
LEFT JOIN "_s5" "_s5"
  ON YEARS.Y = "_s5".Y
ORDER BY
  1 NULLS FIRST
