WITH "_s3" AS (
  SELECT
    CUSTOMER.C_CUSTKEY,
    MAX(CUSTOMER.C_PHONE) AS MAX_C_PHONE
  FROM TPCH.CUSTOMER CUSTOMER
  JOIN TPCH.ORDERS ORDERS
    ON CUSTOMER.C_CUSTKEY = ORDERS.O_CUSTKEY
  GROUP BY
    CUSTOMER.C_CUSTKEY
)
SELECT
  ORDERS.O_ORDERKEY AS "key",
  "_s3".MAX_C_PHONE AS x
FROM TPCH.ORDERS ORDERS
LEFT JOIN "_s3" "_s3"
  ON ORDERS.O_CUSTKEY = "_s3".C_CUSTKEY
ORDER BY
  1 NULLS FIRST
FETCH FIRST 5 ROWS ONLY
